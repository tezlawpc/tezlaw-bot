/**
 * uscis-form-prep.js — fetch a USCIS form, make it fillable, dump its fields
 *
 *   node scripts/uscis-form-prep.js g-28
 *   node scripts/uscis-form-prep.js g-28 --from /path/to/g-28.pdf
 *
 * The second form skips the download, for a machine that can rebuild but not
 * reach uscis.gov (or the other way round: fetch on one, rebuild on the
 * other, which is what the two-machine split here needs).
 *
 * Writes forms/<id>.pdf (the blank we fill) and forms/<id>.fields.json (every
 * fillable box, its kind and its options). Run it on a machine with network,
 * or let the weekly Action run it; the repo's own sandbox cannot reach
 * uscis.gov.
 *
 * WHY A VENDORED BLANK AND NOT A DOWNLOAD AT FILL TIME
 * Two reasons, and the second is the real one.
 *
 *   1. USCIS forms are static-XFA hybrids. pdf-lib — the library this app
 *      already has — cannot open one: the AcroForm dictionary sits behind
 *      object references its parser rejects. Loading and re-saving the file
 *      once rebuilds the cross-reference table and drops the XFA layer,
 *      leaving a plain AcroForm PDF that pdf-lib fills and that Preview,
 *      Chrome and Acrobat all render identically.
 *
 *   2. A form filled for a client has to be filled on the edition that was
 *      checked. Downloading at fill time means the edition can change between
 *      the field map being verified and the form being filled, and a map
 *      built for the old edition puts the right answer in the wrong box.
 *      Committing the blank makes the edition a fact in the repository.
 *
 * THE TOOLTIP IS THE ANCHOR
 * Every field on a USCIS form carries a /TU tooltip holding the printed label
 * verbatim — "Part 3 ... 5. I enter my appearance ... Select Requestor." Those
 * labels are the only reliable way to know which box is which, because the
 * internal names are not: on the G-28 the client's name sits in fields called
 * Pt3Line5a/5b/5c but prints as items 6.a-6.c, and the five appearance
 * checkboxes are all called Line4_Checkbox while printing as item 5. Their
 * export values are worse — /R is Requestor and /B is Respondent, so reading
 * the letters would put a removal client in the wrong capacity on every
 * filing. So the tooltip goes into the dump beside each name, and
 * check-uscis-g28.js asserts every mapped field's tooltip still says what the
 * map thinks it says. That is what makes an edition change fail loudly.
 *
 * WHAT STRIPPING XFA COSTS
 * The PDF417 barcodes USCIS prints at the top of each page are generated by
 * the form's own XFA script from what you type. A rebuilt form cannot
 * generate them, so they stay blank — exactly as they are on a form filled in
 * by hand. The field map and the printed text are unaffected.
 */

const fs = require("fs");
const path = require("path");
const F = require("../uscis-forms");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "forms");

async function main() {
  const id = (process.argv[2] || "").toLowerCase();
  if (!id) {
    console.error("usage: node scripts/uscis-form-prep.js <form-id>   e.g. g-28");
    process.exit(2);
  }
  if (!F.FORMS.some((f) => f.id === id)) {
    console.error(`${id} is not in uscis-forms.js FORMS — add it there first.`);
    process.exit(2);
  }

  const url = F.urlFor(id);
  const fromIdx = process.argv.indexOf("--from");
  const fromPath = fromIdx > 0 ? process.argv[fromIdx + 1] : null;
  let raw;
  if (fromPath) {
    console.log(`reading ${fromPath}`);
    raw = fs.readFileSync(fromPath);
  } else {
    console.log(`fetching ${url}`);
    raw = await F.download(url);
  }
  const ed = await F.readEdition(raw);
  if (!ed.ok) {
    console.error(`could not read the edition off ${id}: ${ed.reason}`);
    console.error("Refusing to vendor a form whose edition we cannot state.");
    process.exit(1);
  }
  console.log(`${id.toUpperCase()}  edition ${ed.edition}  OMB ${ed.omb} expires ${ed.expires}`);

  // The rebuild, then the proof. pdf-lib cannot do the rebuild — it cannot
  // load one of these files well enough to save it again — so that one step
  // runs through pypdf. pdf-lib then has to open the result and find fields,
  // which is the only check that matters: it is the library that will fill it.
  fs.mkdirSync(OUT, { recursive: true });
  const tmp = path.join(OUT, `.${id}.original.pdf`);
  fs.writeFileSync(tmp, raw);
  const out = path.join(OUT, `${id}.pdf`);
  // USCIS ships these forms encrypted — an empty owner password with the
  // permission bits set — so the rebuild needs a crypto backend. On a machine
  // without one, pypdf says so plainly rather than writing half a file.
  const rebuild = require("child_process").spawnSync(
    "python3", [path.join(__dirname, "uscis_form_rebuild.py"), tmp, out],
    { encoding: "utf8" });
  if (rebuild.status === 0) fs.unlinkSync(tmp);
  if (rebuild.status !== 0) {
    console.error(`the original is at ${tmp} — rebuild it on a machine with pypdf and cryptography:`);
    console.error(`  python3 scripts/uscis_form_rebuild.py ${tmp} ${out}`);
    console.error((rebuild.stderr || rebuild.stdout || "python3 could not be run").trim());
    process.exit(1);
  }
  console.log(rebuild.stdout.trim());

  const { PDFDocument, PDFTextField, PDFCheckBox, PDFDropdown,
          PDFRadioGroup, PDFOptionList } = require("pdf-lib");
  const bytes = fs.readFileSync(out);
  const reread = await PDFDocument.load(bytes, { ignoreEncryption: true, updateMetadata: false });
  const form = reread.getForm();
  const fields = form.getFields();
  if (!fields.length) {
    fs.unlinkSync(out);
    console.error(`the rebuilt ${id} has no fillable fields — not shipping it`);
    process.exit(1);
  }

  const kindOf = (f) =>
    f instanceof PDFTextField ? "text"
    : f instanceof PDFCheckBox ? "checkbox"
    : f instanceof PDFDropdown ? "dropdown"
    : f instanceof PDFRadioGroup ? "radio"
    : f instanceof PDFOptionList ? "list" : "other";

  const { PDFName } = require("pdf-lib");
  const tooltipOf = (f) => {
    let tu = f.acroField.dict.get(PDFName.of("TU"));
    if (!tu) {
      const w = f.acroField.getWidgets()[0];
      if (w) tu = w.dict.get(PDFName.of("TU"));
    }
    if (!tu) return null;
    const s = typeof tu.decodeText === "function" ? tu.decodeText() : String(tu);
    return s.replace(/\s+/g, " ").trim() || null;
  };

  const rows = fields.map((f) => {
    const kind = kindOf(f);
    const row = { name: f.getName(), kind, label: tooltipOf(f) };
    if (kind === "text") {
      const n = f.getMaxLength();
      if (n) row.max = n;
      if (f.isMultiline()) row.multiline = true;
      if (f.isReadOnly()) row.readonly = true;
    }
    if (kind !== "text" && kind !== "other") {
      try { row.options = f.getOptions(); } catch { /* some fields refuse */ }
    }
    return row;
  });

  fs.writeFileSync(path.join(OUT, `${id}.fields.json`), JSON.stringify({
    form: id.toUpperCase(),
    source_url: url,
    edition: ed.edition,
    omb: ed.omb,
    omb_expires: ed.expires,
    prepared_on: new Date().toISOString().slice(0, 10),
    pages: reread.getPageCount(),
    note: "Rebuilt from the USCIS original so pdf-lib can fill it; the XFA layer and its generated PDF417 barcodes are gone. See scripts/uscis-form-prep.js.",
    fields: rows,
  }, null, 2) + "\n");

  console.log(`wrote forms/${id}.pdf (${bytes.length} bytes) and forms/${id}.fields.json (${rows.length} fields)`);
}

main().catch((err) => { console.error(err.message); process.exit(1); });
